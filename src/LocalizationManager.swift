// MARK: - Supported App Languages

public enum AppLanguage: String, CaseIterable, Identifiable {
    case english = "en"       // Default
    case spanish = "es"
    case french = "fr"
    case german = "de"
    case portuguese = "pt"
    case italian = "it"
    case japanese = "ja"
    
    public var id: String { rawValue }
    
    public var flag: String {
        switch self {
        case .english: return "🇺🇸"
        case .spanish: return "🇪🇸"
        case .french: return "🇫🇷"
        case .german: return "🇩🇪"
        case .portuguese: return "🇧🇷"
        case .italian: return "🇮🇹"
        case .japanese: return "🇯🇵"
        }
    }
    
    public var displayName: String {
        switch self {
        case .english: return "English"
        case .spanish: return "Español"
        case .french: return "Français"
        case .german: return "Deutsch"
        case .portuguese: return "Português"
        case .italian: return "Italiano"
        case .japanese: return "日本語"
        }
    }
    
    public var flagWithLabel: String {
        "\(flag) \(displayName)"
    }
}

// MARK: - Localization Manager (Persistent & Reactive)

public final class LocalizationManager: ObservableObject {
    public static let shared = LocalizationManager()
    
    private let userDefaultsKey = "battery_scope_language"
    
    @Published public var currentLanguage: AppLanguage {
        didSet {
            UserDefaults.standard.set(currentLanguage.rawValue, forKey: userDefaultsKey)
        }
    }
    
    private init() {
        // Default on first launch: English
        if let saved = UserDefaults.standard.string(forKey: userDefaultsKey),
           let lang = AppLanguage(rawValue: saved) {
            self.currentLanguage = lang
        } else {
            self.currentLanguage = .english
        }
    }
    
    public func setLanguage(_ lang: AppLanguage) {
        withAnimation(.easeInOut(duration: 0.2)) {
            self.currentLanguage = lang
        }
    }
    
    public func tr(_ key: String) -> String {
        if let langDict = strings[currentLanguage], let val = langDict[key] {
            return val
        }
        // Fallback to English
        if let engDict = strings[.english], let val = engDict[key] {
            return val
        }
        return key
    }
    
